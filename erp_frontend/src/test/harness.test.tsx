import { describe, expect, it } from "vitest";
import { render, screen } from "@testing-library/react";

// **‏هذا الملف ليس اختباراً على المنتج، بل شاهدٌ على الأداة.**
//
// المرحلة ٢ مخرَجها «اختبارات راسبة»، والشرط المعلن أن ترسب **بسببها المتوقَّع لا
// بخطأ إعداد**. وهذان لا يفترقان بالنظر إلى تقرير أحمر واحد: مكوّنٌ غائب و jsdom
// غير مهيَّأ كلاهما يُخرِج حمرة. فيلزم طرفٌ ثالث **أخضر** يثبت أن السلسلة —
// ‏esbuild ⟵ JSX ⟵ jsdom ⟵ RTL ⟵ مطابِقات jest-dom — تعمل.
//
// وبه تصير حمرة `MoneyDisplay` **معزوّة**: الأداة تعمل، فالغائب هو المكوّن.
// وهو نظير `M02` الذي رُئي أحمر قبل خضرته: حارس لم يُعرف سبب حمرته ليس حارساً.
//
// يُحذف هذا الملف إن صار في المشروع اختبار أخضر حقيقي يؤدي الدور نفسه.
describe("سلامة أداة الاختبار — شاهد لا اختبار منتج", () => {
  it("H01: يحوّل JSX ويركّب في jsdom ويقرأ بمطابِقات jest-dom", () => {
    render(<p>قياس</p>);

    expect(screen.getByText("قياس")).toBeInTheDocument();
  });

  it("H02: البيئة jsdom لا node — `document` موجود", () => {
    expect(typeof document).toBe("object");
    expect(document.body).toBeTruthy();
  });
});
