      // وأسبابه الثلاثة كانت **خاصة بالقراءات فعلاً لا إعداداً عاماً منسوخاً** —
      // لكنها تُثبت شيئاً أضيق مما استُنتج منها: أنها تمنع إعادة **الأربعمئة**
      // وتمنع **التكرار ثلاثاً**، ولا تمنع إعادة **بلعة شبكة عابرة**. والقراءة
